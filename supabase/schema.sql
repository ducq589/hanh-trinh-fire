create table if not exists public.assets (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  code text not null, name text not null, type text, tier text not null,
  fire_include integer not null default 0, exp_return double precision, target_weight double precision,
  valuation text not null default 'Thị trường', unit text, note text,
  active integer not null default 1, sort_order integer not null default 0, price_source text,
  primary key (user_id, code)
);

create table if not exists public.transactions (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  date text not null, code text not null, type text not null,
  amount double precision, price double precision, qty double precision, fee double precision, tax double precision,
  note text, created_at timestamptz default now()
);
create index if not exists ix_tx_user_code_date on public.transactions(user_id, code, date);

create table if not exists public.prices (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  date text not null, code text not null, price double precision not null, source text,
  is_manual integer not null default 0,
  primary key (user_id, date, code, is_manual)
);

create table if not exists public.market_prices (
  symbol text not null, date text not null, price double precision not null, source text, fetched_at text,
  primary key (symbol, date)
);

create table if not exists public.savings (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null, code text not null, goal text, purpose text, maturity text,
  principal double precision, topup double precision, start_balance double precision,
  interest_gross double precision, note text
);

create table if not exists public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null, target double precision, due_date text,
  unique (user_id, name)
);

create table if not exists public.liabilities (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null, balance double precision, rate double precision,
  monthly_payment double precision, end_date text, note text
);

create table if not exists public.cashflow_items (
  id bigint generated by default as identity primary key,
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  name text not null, grp text not null, member text, amount double precision,
  freq text not null default 'Tháng', note text, sort_order integer not null default 0
);

create table if not exists public.assumptions (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  key text not null, value text, primary key (user_id, key)
);
create table if not exists public.settings (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  key text not null, value text, primary key (user_id, key)
);
create table if not exists public.meta (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  key text not null, value text, primary key (user_id, key)
);

create table if not exists public.snapshots (
  user_id uuid not null default auth.uid() references auth.users(id) on delete cascade,
  date text not null, total_assets double precision, liabilities double precision, net_worth double precision,
  fire_assets double precision, fire_number double precision, fire_progress double precision,
  savings_rate double precision, note text,
  primary key (user_id, date)
);

-- ---------------------------------------------------------------- Row Level Security
do $$
declare t text;
begin
  foreach t in array array['assets','transactions','prices','savings','goals','liabilities',
                           'cashflow_items','assumptions','settings','meta','snapshots']
  loop
    execute format('alter table public.%I enable row level security', t);
    execute format('drop policy if exists own_rows on public.%I', t);
    execute format('create policy own_rows on public.%I for all to authenticated '
                   'using (user_id = auth.uid()) with check (user_id = auth.uid())', t);
    execute format('grant select, insert, update, delete on public.%I to authenticated', t);
    execute format('revoke all on public.%I from anon', t);
  end loop;
end $$;

grant usage, select on all sequences in schema public to authenticated;

alter table public.market_prices enable row level security;
drop policy if exists read_all on public.market_prices;
create policy read_all on public.market_prices for select to authenticated using (true);
grant select on public.market_prices to authenticated;
revoke insert, update, delete on public.market_prices from authenticated, anon;
revoke all on public.market_prices from anon;

-- ---------------------------------------------------------------- Xoá tài khoản (cũng có ở xoa_tai_khoan.sql)
create or replace function public.delete_my_account() returns void
language plpgsql security definer set search_path = '' as $$
begin
  if auth.uid() is null then
    raise exception 'not authenticated';
  end if;
  delete from auth.users where id = auth.uid();
end $$;

revoke all on function public.delete_my_account() from public, anon;
grant execute on function public.delete_my_account() to authenticated;
